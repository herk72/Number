# إزالة المكرر (7 = روسيا فقط)
_seen: set = set()
_CLEAN: list[tuple[str, str, str]] = []
for _d, _f, _n in DIAL_TO_COUNTRY:
    if _d not in _seen:
        _seen.add(_d)
        _CLEAN.append((_d, _f, _n))
DIAL_TO_COUNTRY = _CLEAN

# الترتيب: الأطول بادئة أولاً لضمان الدقة
DIAL_TO_COUNTRY.sort(key=lambda x: -len(x[0]))


def phone_to_country(phone: str) -> tuple[str, str, str]:
    """
    يُرجع (dial_code, flag, country_name) بناءً على بادئة الرقم.
    مثال: '+966501234567' → ('966', '🇸🇦', 'السعودية')
    """
    p = (phone or "").strip().lstrip("+")
    for dial, flag, name in DIAL_TO_COUNTRY:
        if p.startswith(dial):
            return (dial, flag, name)
    return ("00", "🌍", "أخرى")
